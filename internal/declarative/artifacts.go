package declarative

import (
	"bytes"
	"errors"
	"io"
	"maps"
	"os"
	"path/filepath"
	"syscall"
)

var errArtifactConflict = errors.New("generated artifacts differ from the expected previous or desired definitions")

const artifactConflictRemedy = "Generated files differ from server-man's expected output. Configuration remains saved, but publication is blocked. Inspect and preserve this resource's owned artifacts before explicit repair and retry."

// publishArtifacts owns a dedicated resource directory. Existing outputs must
// match either the prior definition or the desired definition (interrupted apply).
// It rejects foreign files and symlinks and never touches workload data.
func publishArtifacts(dir string, previous, desired map[string][]byte) error {
	if !filepath.IsAbs(dir) {
		return errors.New("artifact directory must be absolute")
	}
	if err := os.MkdirAll(dir, 0700); err != nil {
		return err
	}
	info, err := os.Lstat(dir)
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode().Perm()&0077 != 0 {
		return errors.New("artifact directory must be private and not a symlink")
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	if err = checkArtifactOwnership(dir, previous, desired); err != nil {
		return err
	}
	for name, data := range desired {
		if filepath.Base(name) != name || !bytes.HasPrefix(data, []byte(ownedHeader)) && !bytes.HasPrefix(data, []byte("<!-- Generated by server-man; edit the authoritative workload configuration. -->\n")) {
			return errors.New("invalid owned artifact")
		}
		// Create temporary files via the directory handle, preventing path escape.
		temp := "." + name + ".new"
		f, err := root.OpenFile(temp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if err != nil {
			return err
		}
		_, err = f.Write(data)
		if err == nil {
			err = f.Sync()
		}
		e := f.Close()
		if err == nil {
			err = e
		}
		if err == nil {
			err = root.Rename(temp, name)
		}
		if err != nil {
			_ = root.Remove(temp)
			return err
		}
	}
	for name := range previous {
		if _, ok := desired[name]; ok {
			continue
		}
		if err = root.Remove(name); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	d, err := root.Open(".")
	if err != nil {
		return err
	}
	defer d.Close()
	if err := d.Sync(); err != nil {
		return err
	}
	// A private checksum inventory is the last publication stage. If its
	// atomic/synced update fails, the apply journal must retain a failure.
	return writeArtifactManifest(dir, desired)
}
func readArtifact(root *os.Root, name string) ([]byte, error) {
	f, err := root.OpenFile(name, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Size() > MaxConfigBytes {
		return nil, errors.New("invalid artifact file")
	}
	return io.ReadAll(io.LimitReader(f, MaxConfigBytes+1))
}

// Check ownership before destructive backend calls as well as before publication.
func checkArtifactOwnership(dir string, previous, desired map[string][]byte) error {
	// The prior sidecar must describe either the previous complete output or
	// the desired complete output (a previous interrupted publication). A
	// well-formed but unrelated checksum inventory does not prove ownership.
	// Absence is allowed for initial adoption, but never authorizes unknown
	// artifact bytes in the resource directory.
	manifest, _, err := readArtifactManifest(dir)
	if err == nil {
		if !maps.Equal(manifest.Files, artifactManifestFor(previous).Files) &&
			!maps.Equal(manifest.Files, artifactManifestFor(desired).Files) {
			return errArtifactConflict
		}
	} else if !os.IsNotExist(err) {
		return errArtifactConflict
	}
	info, err := os.Lstat(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode().Perm()&0077 != 0 {
		return errors.New("unsafe artifact directory")
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	if len(entries) > 256 {
		return errors.New("artifact file limit exceeded")
	}
	for _, entry := range entries {
		actual, err := readArtifact(root, entry.Name())
		if err != nil {
			return err
		}
		old, was := previous[entry.Name()]
		next, want := desired[entry.Name()]
		if (!was || !bytes.Equal(old, actual)) && (!want || !bytes.Equal(next, actual)) {
			return errArtifactConflict
		}
	}
	return nil
}

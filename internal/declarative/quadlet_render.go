package declarative

import (
	"errors"
	"fmt"
	"maps"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const ownedHeader = "# Generated by server-man; edit the authoritative workload configuration.\n"

func quadletBase(service, container string) string {
	return "sm-" + service + "-" + digest([]byte(service + "/" + container))[:16]
}
func quadletNetwork(service string) string { return "sm-network-" + digest([]byte(service))[:24] }

// unitValue quotes one systemd/Quadlet token and escapes specifier expansion.
func unitValue(s string) string { return strconv.Quote(strings.ReplaceAll(s, "%", "%%")) }
func quadletUnits(c Config, id string) []string {
	names := slices.Sorted(maps.Keys(c.Services[id].Containers))
	units := make([]string, 0, len(names))
	for _, name := range names {
		units = append(units, quadletBase(id, name)+".service")
	}
	return units
}
func RenderQuadlet(store Store, c Config, key string) (map[string][]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	kind, id, ok := strings.Cut(key, "/")
	s, exists := c.Services[id]
	if !ok || kind != "service" || !exists || s.Kind != "container" || s.Engine != "podman" || s.Backend != "quadlet" {
		return nil, errors.New("resource is not a Podman Quadlet application")
	}
	files := map[string][]byte{}
	network := quadletNetwork(id)
	files[network+".network"] = []byte(ownedHeader + "[Network]\nNetworkName=" + network + "\n")
	fingerprint := containerRuntimeFingerprint(c, key)
	for _, name := range slices.Sorted(maps.Keys(s.Containers)) {
		v := s.Containers[name]
		var b strings.Builder
		b.WriteString(ownedHeader + "[Unit]\nDescription=server-man container\n")
		for _, dep := range s.DependsOn {
			ds := c.Services[dep]
			if ds.Engine != "podman" || ds.Backend != "quadlet" {
				return nil, errors.New("Quadlet dependencies currently require Quadlet applications")
			}
			for _, unit := range quadletUnits(c, dep) {
				fmt.Fprintf(&b, "Requires=%s\nAfter=%s\n", unit, unit)
			}
		}
		b.WriteString("\n[Container]\n")
		fmt.Fprintf(&b, "Image=%s\nContainerName=%s\nNetwork=%s.network\nNetworkAlias=%s\n", unitValue(v.Image), quadletBase(id, name), network, name)
		fmt.Fprintf(&b, "Label=io.server-man.service=%s\nLabel=io.server-man.container=%s\nLabel=io.server-man.fingerprint=%s\n", id, name, fingerprint)
		b.WriteString("NoNewPrivileges=true\n")
		for _, port := range v.Ports {
			fmt.Fprintf(&b, "PublishPort=%s\n", port)
		}
		for _, env := range slices.Sorted(maps.Keys(v.Environment)) {
			fmt.Fprintf(&b, "Environment=%s\n", unitValue(env+"="+v.Environment[env]))
		}
		for _, ref := range v.EnvFiles {
			path := store.Resolve(c.Secrets[ref])
			if !filepath.IsAbs(path) {
				return nil, errors.New("manifest path must be absolute")
			}
			fmt.Fprintf(&b, "EnvironmentFile=%s\n", unitValue(path))
		}
		for _, m := range v.Mounts {
			path := store.Resolve(c.Storage[m.Storage].Path)
			if !filepath.IsAbs(path) || strings.ContainsAny(path, ":\n\r") || strings.Contains(m.Target, ":") {
				return nil, errors.New("mount path cannot be represented by Quadlet volume syntax")
			}
			suffix := ":rw"
			if m.ReadOnly {
				suffix = ":ro"
			}
			fmt.Fprintf(&b, "Volume=%s\n", unitValue(path+":"+m.Target+suffix))
		}
		if v.MemoryMiB > 0 {
			fmt.Fprintf(&b, "Memory=%dm\n", v.MemoryMiB)
		}
		if len(v.Command) > 0 {
			args := make([]string, len(v.Command))
			for i, arg := range v.Command {
				args[i] = unitValue(strings.ReplaceAll(arg, "$", "$$"))
			}
			fmt.Fprintf(&b, "Exec=%s\n", strings.Join(args, " "))
		}
		b.WriteString("\n[Service]\nRestart=on-failure\nRestartSec=5\nTimeoutStartSec=900\nTimeoutStopSec=90\n")
		if v.CPUs > 0 {
			fmt.Fprintf(&b, "CPUQuota=%d%%\n", v.CPUs*100)
		}
		if s.Enabled {
			b.WriteString("\n[Install]\nWantedBy=default.target\n")
		}
		files[quadletBase(id, name)+".container"] = []byte(b.String())
	}
	return files, nil
}

// Boot policy and display metadata do not change container execution settings.
func containerRuntimeFingerprint(c Config, key string) string {
	_, id, _ := strings.Cut(key, "/")
	s := c.Services[id]
	s.Enabled = false
	s.Name = ""
	s.Description = ""
	c.Services = maps.Clone(c.Services)
	c.Services[id] = s
	return resourceFingerprint(c, key)
}

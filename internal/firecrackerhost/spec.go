// Package firecrackerhost isolates Firecracker's narrow privileged operations.
// This package does not import declarative, avoiding a helper dependency cycle.
package firecrackerhost

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"net"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const (
	RuntimePath = "/usr/local/libexec/server-man-firecracker-runtime"
	BasePath    = "/var/lib/server-man-firecracker"
	JailerPath  = "/usr/bin/jailer"
	VMMPath     = "/usr/bin/firecracker"
	Systemctl   = "/usr/bin/systemctl"
)
var (
	idPattern = regexp.MustCompile("^[a-z][a-z0-9_-]{0,62}$")
	uuidPattern = regexp.MustCompile("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
	bridgePattern = regexp.MustCompile("^[A-Za-z0-9][A-Za-z0-9_.-]{0,14}$")
	opaquePattern = regexp.MustCompile("^fc[0-9a-f]{20}$")
)
const header = "# Generated by server-man; edit the authoritative workload configuration.\n"

type Spec struct {
	ResourceID string   `json:"resource_id"`
	UUID       string   `json:"uuid"`
	Kernel     string   `json:"kernel"`
	Disks      []string `json:"disks"`
	Bridge     string   `json:"bridge"`
	MAC        string   `json:"mac"`
	CPUs       int      `json:"cpus"`
	MemoryMiB  int      `json:"memory_mib"`
	BootArgs   string   `json:"boot_args"`
	Enabled    bool     `json:"enabled"`
	// UID/GID are trusted identity values, set by the root helper from sudo.
	UID        int      `json:"uid"`
	GID        int      `json:"gid"`
}
type Observation struct {
	Registered    bool   `json:"registered"`
	Running       bool   `json:"running"`
	Matches       bool   `json:"matches"`
	ActiveMatches bool   `json:"active_matches"`
	State         string `json:"state"`
	Enabled       bool   `json:"enabled"`
}
func Identity(uid int, id string) string {
	sha := sha256.Sum256([]byte(strconv.Itoa(uid) + ":" + id))
	return "fc" + hex.EncodeToString(sha[:])[:20]
}
func TapName(uuid string) string {
	sha := sha256.Sum256([]byte(uuid))
	return "smfc" + hex.EncodeToString(sha[:])[:10]
}
func Root(id string) string { return filepath.Join(BasePath, "workloads", id) }
func JailRoot(id string) string { return filepath.Join(BasePath, "jails", "firecracker", id, "root") }
func UnitName(id string) string { return "sm-firecracker-" + id + ".service" }
func UnitPath(id string) string { return filepath.Join("/etc/systemd/system", UnitName(id)) }

func (s Spec) Validate() error {
	if !idPattern.MatchString(s.ResourceID) || !uuidPattern.MatchString(s.UUID) || !bridgePattern.MatchString(s.Bridge) ||
		s.UID < 1 || s.GID < 1 || !opaquePattern.MatchString(Identity(s.UID, s.ResourceID)) {
		return errors.New("invalid Firecracker VM identity or bridge")
	}
	mac, err := net.ParseMAC(s.MAC)
	if err != nil || len(mac) != 6 || mac[0]&1 != 0 || mac.String() != s.MAC {
		return errors.New("invalid Firecracker MAC")
	}
	if s.CPUs < 1 || s.CPUs > 32 || s.MemoryMiB < 128 || s.MemoryMiB > 262144 || len(s.Disks) < 1 || len(s.Disks) > 8 {
		return errors.New("invalid Firecracker resources")
	}
	if len(s.BootArgs) > 2048 || strings.ContainsAny(s.BootArgs, "\x00\r\n") {
		return errors.New("invalid Firecracker boot arguments")
	}
	files := append([]string{s.Kernel}, s.Disks...)
	seen := map[string]bool{}
	for _, file := range files {
		if !filepath.IsAbs(file) || filepath.Clean(file) != file || len(file) > 4096 ||
			strings.ContainsAny(file, "\x00\r\n") || seen[file] {
			return errors.New("invalid or duplicated Firecracker source path")
		}
		seen[file] = true
	}
	return nil
}
type boot struct {
	Kernel string `json:"kernel_image_path"`
	Args string `json:"boot_args"`
}
type machine struct {
	CPUs int `json:"vcpu_count"`
	Memory int `json:"mem_size_mib"`
	SMT bool `json:"smt"`
}
type disk struct {
	ID string `json:"drive_id"`
	Path string `json:"path_on_host"`
	Root bool `json:"is_root_device"`
	ReadOnly bool `json:"is_read_only"`
}
type nic struct {
	ID string `json:"iface_id"`
	MAC string `json:"guest_mac"`
	Tap string `json:"host_dev_name"`
}
type nativeConfig struct {
	Boot boot `json:"boot-source"`
	Machine machine `json:"machine-config"`
	Drives []disk `json:"drives"`
	NIC []nic `json:"network-interfaces"`
}
func (s Spec) NativeJSON() ([]byte,error) {
	if err := s.Validate(); err != nil { return nil,err }
	args := s.BootArgs
	if args == "" { args = "console=ttyS0 reboot=k panic=1 root=/dev/vda rw" }
	config := nativeConfig{
		Boot:boot{"/kernel",args},
		Machine:machine{s.CPUs,s.MemoryMiB,false},
		Drives:make([]disk,0,len(s.Disks)),
		NIC:[]nic{{"eth0",s.MAC,TapName(s.UUID)}},
	}
	for n := range s.Disks {
		id,path:="rootfs","/disks/root"
		if n!=0 { id,path=fmt.Sprintf("disk%d",n),fmt.Sprintf("/disks/disk%d",n) }
		config.Drives=append(config.Drives,disk{id,path,n==0,false})
	}
	bytes,err:=json.MarshalIndent(config,"","  ")
	return append(bytes,'\n'),err
}
func (s Spec) Unit() ([]byte,error) {
	if err := s.Validate(); err != nil {return nil,err}
	id:=Identity(s.UID,s.ResourceID)
	// Only fixed paths and validated identifiers/integers occur in directives.
	unit:=fmt.Sprintf(`[Unit]
Description=server-man Firecracker microVM %s
Wants=network-online.target
After=network-online.target
[Service]
Type=exec
Delegate=yes
ExecStartPre=%s prepare %s
ExecStart=%s --id %s --exec-file %s --uid %d --gid %d --chroot-base-dir %s/jails --cgroup-version 2 --resource-limit no-file=1024 -- --api-sock /api.socket --config-file /vm.json
ExecStopPost=%s cleanup %s
Restart=no
TimeoutStartSec=60s
TimeoutStopSec=30s
MemoryMax=%dM
TasksMax=512
LogRateLimitIntervalSec=30s
LogRateLimitBurst=100
StandardOutput=journal
StandardError=journal
[Install]
WantedBy=multi-user.target
`,id,RuntimePath,id,JailerPath,id,VMMPath,s.UID,s.GID,BasePath,RuntimePath,id,s.MemoryMiB+256)
	return []byte(header+unit),nil
}
